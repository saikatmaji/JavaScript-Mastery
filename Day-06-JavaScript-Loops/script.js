// =========================================
// For Loop
// =========================================

// Loops are used to repeat a block of code.


// The for loop is used when the number of iterations is known before the loop starts.

// Syntax:
// for (initialization; condition; increment/decrement) {
//   // code to execute
// }


// Example:
// Print numbers from 1 to 100

for (let i = 1; i <= 100; i++) {
  console.log(i);
}