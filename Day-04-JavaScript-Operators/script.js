// Arithmetic operators are used to perform mathematical calculations.

// Operators:
// +  Addition
// -  Subtraction
// *  Multiplication
// /  Division
// %  Modulus (Remainder)
// ** Exponentiation (Power)


// Addition (+)

// Number Addition
// 1 + 2 = 3

// String Concatenation
// "ha" + "rsh" = "harsh"


// Subtraction (-)

// 12 - 2 = 10


// Multiplication (*)

// 12 * 2 = 24


// Division (/)

// 12 / 2 = 6


// Modulus (%)

// Returns the remainder after division.
// 12 % 5 = 2




